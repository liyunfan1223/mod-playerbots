CREATE TABLE IF NOT EXISTS `playerbots_living_bonds` (
    `bot` INT UNSIGNED NOT NULL,
    `other` INT UNSIGNED NOT NULL,
    `score` SMALLINT NOT NULL DEFAULT 0,
    `quests` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `bosses` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `battlegrounds` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `minutes` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `helps` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `duels` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `kills` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `ninjas` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `slights` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `last_seen` INT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (`bot`, `other`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
