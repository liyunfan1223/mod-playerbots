"""Render a Markdown benchmark report from a bench run's test_results.json.

Usage:
    python make_benchmarks.py [test_results.json] [BENCHMARKS.md]

Reads the "bench <name>" entries the runner emits for "<name>*N" scenario tokens
and writes a per-bench kill-time table, a pooled per-spec DPS table, and the raw
per-bench notes. Scenario-agnostic: whatever benches are in the file get reported.
"""

import json
import re
import statistics
import sys
from collections import defaultdict
from pathlib import Path

HEAD_RE = re.compile(
    r"runs (\d+): (\d+) passed \| kill avg (\d+)s min (\d+)s max (\d+)s \| deaths avg ([\d.]+)")
SPEC_RE = re.compile(
    r"spec (.+?)\s+x(\d+): dps avg (\d+) min (\d+) max (\d+) \| ilvl (\d+)")

HEADER = """# Benchmark report

Per-bench kill times and per-spec DPS pooled from a bench run's `test_results.json`.
Generated by `make_benchmarks.py`.
"""


def load_results(src: Path):
    """Split a test_results.json into bench entries (by name) and per-run lists."""
    data = json.loads(src.read_text(encoding="utf-8"))
    benches: dict[str, dict] = {}
    runs: dict[str, list] = defaultdict(list)
    for entry in data["results"]:
        if entry["name"].startswith("bench "):
            benches[entry["name"][6:]] = entry
        else:
            runs[entry["name"].split("#")[0]].append(entry)
    return benches, runs


def failed_runs_section(lines: list, runs: dict) -> None:
    lines.append("## Failed runs\n")
    failed = [run for name in sorted(runs) for run in runs[name] if not run["passed"]]
    for run in failed:
        lines.append(f"- **{run['name']}** failed at '{run.get('failedStep', '')}' "
                     f"(deaths {run['metrics'].get('bot_deaths', '?')})")
    if not failed:
        lines.append("None.")


def main() -> None:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("test_results.json")
    dst = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).parent / "BENCHMARKS.md"

    benches, runs = load_results(src)
    order = sorted(benches)

    lines = [HEADER, "## Per bench\n"]
    lines.append("| Bench | Pass | Kill avg | min | max | Deaths avg |")
    lines.append("|---|---|---|---|---|---|")

    spec_samples: dict[str, list] = defaultdict(list)
    spec_ilvl: dict[str, list] = defaultdict(list)
    for name in order:
        bench = benches[name]
        head = HEAD_RE.search(bench["notes"][0]) if bench["notes"] else None
        if head:
            total, passed, avg, mn, mx, deaths = head.groups()
            lines.append(f"| {name} | {passed}/{total} | {avg}s | {mn}s | {mx}s | {deaths} |")
        for note in bench["notes"][1:]:
            if m := SPEC_RE.search(note):
                spec, count, dps_avg, _, _, ilvl = m.groups()
                spec_samples[spec].append((int(count), float(dps_avg)))
                spec_ilvl[spec].append(int(ilvl))

    lines.append("\n## DPS by spec (all benches pooled)\n")
    lines.append("| Spec | Samples | DPS avg | ilvl avg |")
    lines.append("|---|---|---|---|")
    rows = []
    for spec, samples in spec_samples.items():
        n = sum(count for count, _ in samples)
        avg = sum(count * dps for count, dps in samples) / n
        rows.append((avg, spec, n, round(statistics.mean(spec_ilvl[spec]))))
    for avg, spec, n, ilvl in sorted(rows, reverse=True):
        lines.append(f"| {spec} | {n} | {avg:.0f} | {ilvl} |")

    lines.append("\n## Per-bench details\n")
    for name in order:
        lines.append(f"### {name}\n")
        lines.append("```")
        lines.extend(benches[name]["notes"])
        lines.append("```\n")

    failed_runs_section(lines, runs)

    dst.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {dst} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
