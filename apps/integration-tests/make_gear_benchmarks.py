"""Render a gear-tier comparison from a bench run's test_results.json.

Usage:
    python make_gear_benchmarks.py [test_results.json] [GEAR_BENCHMARKS.md] [--variants=a,b,...]

Groups benches named "<base>" and "<base>_<variant>" and lays kill times and per-spec
DPS side by side across the variant tiers. Variants are auto-detected (a "<base>_<v>"
whose plain "<base>" is also a bench); use --variants to add tiers that have no plain
baseline bench. Scenario-agnostic: whatever tiers are present get compared.
"""

import statistics
import sys
from collections import defaultdict
from pathlib import Path

from make_benchmarks import HEAD_RE, SPEC_RE, failed_runs_section, load_results

BASELINE = "base"


def detect_variants(names):
    """A trailing "_<tok>" is a variant when the plain "<base>" is also a bench."""
    names = set(names)
    found = set()
    for name in names:
        base, sep, tok = name.rpartition("_")
        if sep and base in names:
            found.add(tok)
    return found


def split_variant(name, variants):
    base, sep, tok = name.rpartition("_")
    if sep and tok in variants:
        return base, tok
    return name, BASELINE


def head_stats(bench):
    m = HEAD_RE.search(bench["notes"][0]) if bench and bench["notes"] else None
    return m.groups() if m else None


def spec_stats(benches):
    """Pooled weighted per-spec dps/ilvl over the given benches."""
    dps, ilvl = defaultdict(list), defaultdict(list)
    for bench in benches:
        for note in bench["notes"][1:]:
            if m := SPEC_RE.search(note):
                spec, count, avg, _, _, il = m.groups()
                dps[spec].append((int(count), float(avg)))
                ilvl[spec].append(int(il))
    out = {}
    for spec, samples in dps.items():
        n = sum(c for c, _ in samples)
        out[spec] = (sum(c * d for c, d in samples) / n, n, round(statistics.mean(ilvl[spec])))
    return out


def parse_args(argv):
    variants, positional = set(), []
    it = iter(argv)
    for a in it:
        if a.startswith("--variants="):
            variants |= {v for v in a.split("=", 1)[1].split(",") if v}
        elif a == "--variants":
            variants |= {v for v in next(it, "").split(",") if v}
        else:
            positional.append(a)
    return positional, variants


def main() -> None:
    positional, cli_variants = parse_args(sys.argv[1:])
    src = Path(positional[0]) if positional else Path("test_results.json")
    dst = Path(positional[1]) if len(positional) > 1 else Path(__file__).parent / "GEAR_BENCHMARKS.md"

    benches, runs = load_results(src)
    variants = detect_variants(benches) | cli_variants

    grouped: dict[str, dict[str, str]] = defaultdict(dict)  # base -> {tier: bench name}
    for name in benches:
        base, tier = split_variant(name, variants)
        grouped[base][tier] = name
    cols = [c for c in [BASELINE, *sorted(variants)] if any(c in tiers for tiers in grouped.values())]

    header = ("# Gear-tier benchmark\n\nKill times and per-spec DPS across gear tiers, grouped by "
              "`<base>` / `<base>_<variant>` bench names. Generated by `make_gear_benchmarks.py`.\n")
    lines = [header, "## Kill time by tier\n"]
    lines.append("| Bench | " + " | ".join(f"{c} pass | {c} kill" for c in cols) + " |")
    lines.append("|---" * (1 + 2 * len(cols)) + "|")
    for base in sorted(grouped):
        cells = []
        for c in cols:
            h = head_stats(benches.get(grouped[base].get(c)))
            cells += [f"{h[1]}/{h[0]} | {h[2]}s"] if h else ["- | -"]
        lines.append(f"| {base} | " + " | ".join(cells) + " |")

    tier_specs = {c: spec_stats([benches[grouped[b][c]] for b in grouped if c in grouped[b]]) for c in cols}
    ref = cols[-1]
    all_specs = sorted({s for st in tier_specs.values() for s in st},
                       key=lambda s: -(tier_specs[ref].get(s) or next(
                           (tier_specs[c][s] for c in cols if s in tier_specs[c]), (0,)))[0])
    lines.append("\n## DPS by spec and tier\n")
    lines.append("| Spec | " + " | ".join(f"{c} dps | {c} ilvl" for c in cols) + " |")
    lines.append("|---" * (1 + 2 * len(cols)) + "|")
    for spec in all_specs:
        cells = [f"{tier_specs[c][spec][0]:.0f} | {tier_specs[c][spec][2]}" if spec in tier_specs[c]
                 else "- | -" for c in cols]
        lines.append(f"| {spec} | " + " | ".join(cells) + " |")

    lines.append("\n## Per-bench details\n")
    for name in sorted(benches):
        lines.append(f"### {name}\n")
        lines.append("```")
        lines.extend(benches[name]["notes"])
        lines.append("```\n")

    failed_runs_section(lines, runs)

    dst.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {dst} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
